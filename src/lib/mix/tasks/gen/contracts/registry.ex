defmodule Mix.Tasks.Gen.Contracts.Registry do
  @moduledoc false

  alias Mix.Tasks.Gen.Contracts.{Discriminant, EnumValues, Renderer, TypespecParser}

  @handlers [Discriminant, EnumValues]

  def list_contract_modules do
    :network_defense
    |> Application.spec(:modules)
    |> Enum.filter(&contract?/1)
    |> Enum.sort()
  end

  def generate(module) do
    context = %{
      module: module,
      metadata: module.contract_meta(),
      fields: TypespecParser.parse(module),
      ts_name: derive_ts_name(module)
    }

    Enum.find_value(@handlers, fn handler ->
      case handler.render(context) do
        {:emit, output} -> output
        :skip -> nil
      end
    end) || Renderer.interface(context.ts_name, context.fields)
  end

  def generate_all do
    File.write!(output_path(), render_all())
  end

  def render_all do
    header =
      "// AUTO-GENERATED by mix gen.contracts -- DO NOT EDIT\n// Source: lib/network_defense_web/live/web/dashboard/contracts/\n\n"

    body = Enum.map_join(list_contract_modules(), "\n\n", &generate/1)

    header <> body <> "\n"
  end

  def derive_ts_name(mod) do
    mod
    |> Module.split()
    |> List.last()
  end

  defp contract?(module) do
    Code.ensure_loaded?(module) and function_exported?(module, :__contract__, 0) and
      module.__contract__()
  end

  defp output_path do
    Path.join(File.cwd!(), "assets/svelte/dashboard/contracts.generated.ts")
  end
end
