defmodule Mix.Tasks.Gen.Contracts.Registry do
  @moduledoc false

  alias Mix.Tasks.Gen.Contracts.{
    Discriminant,
    EnumValues,
    ErrorCodes,
    Renderer,
    RuntimeMetadata,
    TypespecParser
  }

  @handlers [Discriminant, EnumValues]
  def list_contract_modules(categories) do
    categories = category_names(categories)

    :network_defense
    |> Application.spec(:modules)
    |> Enum.filter(&category_contract?(&1, categories))
    |> contract_closure()
    |> Enum.sort()
  end

  def generate(module) do
    context = %{
      module: module,
      metadata: module.contract_meta(),
      fields: TypespecParser.parse(module),
      ts_name: derive_ts_name(module)
    }

    Enum.find_value(@handlers, fn handler ->
      case handler.render(context) do
        {:emit, output} -> output
        :skip -> nil
      end
    end) ||
      Renderer.source_comment(module) <>
        "\n" <> Renderer.interface(context.module, context.fields)
  end

  def generate_all do
    path = output_path()
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, render_all())
    File.write!(runtime_output_path(), render_runtime_metadata())
    generate_import_modules()
  end

  def render_all do
    header = "// AUTO-GENERATED by mix gen.contracts -- DO NOT EDIT\n// Source: all contracts\n\n"

    body = [ErrorCodes.render() | Enum.map(list_contract_modules(:all), &generate/1)]
    body = Enum.join(body, "\n\n")

    header <> body <> "\n"
  end

  def render_runtime_metadata do
    inspector_contract_modules()
    |> RuntimeMetadata.render()
  end

  @namespace_paths %{
    "NetworkDefense.Errors" => "errors",
    "NetworkDefense.Graph.Contracts" => "graph",
    "NetworkDefense.Graph.Contracts.Data" => "graph/data",
    "NetworkDefense.Optimization.Contracts" => "optimization",
    "NetworkDefense.Simulation.Contracts" => "simulation",
    "NetworkDefenseWeb.Contracts.Dashboard" => "dashboard"
  }

  def generate_import_modules do
    dir = import_modules_dir()
    File.rm_rf!(dir)

    render_import_modules()
    |> Enum.each(fn {rel_path, content} ->
      full = Path.join(dir, rel_path)
      File.mkdir_p!(Path.dirname(full))
      File.write!(full, content)
    end)
  end

  def render_import_modules do
    entries =
      list_contract_modules(:all)
      |> Enum.sort()
      |> Enum.reduce(%{"errors" => [{"ErrorCode", "NetworkDefense.Errors.ErrorCode"}]}, fn module,
                                                                                           acc ->
        namespace = Renderer.contract_namespace(module)
        path = path_for_namespace(namespace)
        leafs = Enum.map(owned_type_names(module), &{&1, namespace <> "." <> &1})
        Map.update(acc, path, leafs, &(&1 ++ leafs))
      end)

    Enum.sort(Map.keys(entries))
    |> Enum.map(fn path ->
      rel_path = path <> ".ts"

      aliases =
        entries[path]
        |> Enum.sort()
        |> Enum.map_join("", fn {name, ref} ->
          "export type #{name} = __Contracts.#{ref};\n"
        end)

      runtime_exports = runtime_exports(path)

      content =
        "// AUTO-GENERATED by mix gen.contracts -- DO NOT EDIT\nimport type * as __Contracts from \"#{relative_import_path(rel_path)}\";\n\n" <>
          aliases <> runtime_exports

      {rel_path, content}
    end)
  end

  def import_modules_dir, do: Path.join(File.cwd!(), "assets/svelte/contracts.generated")

  defp relative_import_path(rel_path) do
    import_path = Path.join("assets/svelte/contracts.generated", rel_path)

    "assets/svelte/contracts.generated.ts"
    |> Path.relative_to(Path.dirname(import_path))
    |> Path.rootname()
  end

  defp owned_type_names(module) do
    leaf = derive_ts_name(module)

    case module.contract_meta() do
      %{discriminant: config} ->
        variant_names =
          config
          |> Keyword.get(:variants, [])
          |> Enum.map(fn {tag, _module} -> "#{Macro.camelize(to_string(tag))}#{leaf}" end)

        [leaf | variant_names]

      _metadata ->
        [leaf]
    end
  end

  defp path_for_namespace("NetworkDefenseWeb.Contracts.Dashboard." <> rest) do
    segments = rest |> String.split(".") |> Enum.map_join("/", &Macro.underscore/1)
    "dashboard/" <> segments
  end

  defp path_for_namespace(namespace), do: Map.fetch!(@namespace_paths, namespace)

  def derive_ts_name(mod) do
    mod
    |> Module.split()
    |> List.last()
  end

  defp category_contract?(module, :all) do
    contract?(module) and function_exported?(module, :contract_category, 0) and
      is_atom(module.contract_category())
  end

  defp category_contract?(module, categories) do
    contract?(module) and function_exported?(module, :contract_category, 0) and
      case module.contract_category() do
        category when is_atom(category) -> category_name(category) in categories
        _category -> false
      end
  end

  defp contract?(module) do
    Code.ensure_loaded?(module) and function_exported?(module, :__contract__, 0) and
      module.__contract__()
  end

  defp contract_closure(modules), do: expand_contracts(modules, %{}) |> Map.keys()

  defp expand_contracts([], modules), do: modules

  defp expand_contracts([module | rest], modules) do
    if Map.has_key?(modules, module) do
      expand_contracts(rest, modules)
    else
      dependencies =
        module
        |> contract_dependencies()
        |> Enum.filter(&contract?/1)

      expand_contracts(dependencies ++ rest, Map.put(modules, module, true))
    end
  end

  defp contract_dependencies(module) do
    typespec_dependencies =
      module
      |> TypespecParser.parse()
      |> Enum.flat_map(fn {_field, type_ast} -> TypespecParser.referenced_modules(type_ast) end)

    metadata_dependencies =
      case module.contract_meta() do
        %{discriminant: config} -> config |> Keyword.get(:variants, []) |> Keyword.values()
        _metadata -> []
      end

    typespec_dependencies ++ metadata_dependencies
  end

  defp inspector_contract_modules do
    [
      NetworkDefense.Graph.Contracts.GraphContract,
      NetworkDefense.Graph.Contracts.Node,
      NetworkDefense.Graph.Contracts.Edge
    ]
    |> contract_closure()
    |> Enum.sort()
  end

  def output_path, do: Path.join(File.cwd!(), "assets/svelte/contracts.generated.ts")

  def runtime_output_path,
    do: Path.join(File.cwd!(), "assets/svelte/contracts.generated.runtime.ts")

  defp runtime_exports("graph") do
    "\nexport { edgeDataContracts, nodeDataContracts } from \"../contracts.generated.runtime\";\n"
  end

  defp runtime_exports("graph/data") do
    "\nexport { contractMetadata } from \"../../contracts.generated.runtime\";\nexport type { ContractMetadata, FieldKind, FieldMetadata } from \"../../contracts.generated.runtime\";\n"
  end

  defp runtime_exports(_path), do: ""

  defp category_names(:all), do: :all
  defp category_names("all"), do: :all
  defp category_names([]), do: raise(ArgumentError, "at least one contract category is required")

  defp category_names(categories) when is_list(categories) do
    categories = categories |> Enum.map(&category_name/1) |> Enum.uniq()

    cond do
      categories == ["all"] ->
        :all

      "all" in categories ->
        raise ArgumentError, "all cannot be combined with other contract categories"

      true ->
        categories
    end
  end

  defp category_names(category), do: [category_name(category)]

  defp category_name(category) when is_atom(category),
    do: category |> Atom.to_string() |> category_name()

  defp category_name(category) when is_binary(category) do
    if Regex.match?(~r/^[a-z][a-z0-9_]*$/, category) do
      category
    else
      raise ArgumentError,
            "category must contain only lowercase letters, numbers, and underscores"
    end
  end

  defp category_name(_category), do: raise(ArgumentError, "category must be an atom or string")
end
