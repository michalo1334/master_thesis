defmodule Mix.Tasks.Gen.Contracts.Registry do
  @moduledoc false

  alias Mix.Tasks.Gen.Contracts.{Discriminant, EnumValues, Renderer, TypespecParser}

  @handlers [Discriminant, EnumValues]
  def list_contract_modules(category) do
    category = category_name(category)

    :network_defense
    |> Application.spec(:modules)
    |> Enum.filter(&contract?(&1, category))
    |> Enum.sort()
  end

  def generate(module) do
    context = %{
      module: module,
      metadata: module.contract_meta(),
      fields: TypespecParser.parse(module),
      ts_name: derive_ts_name(module)
    }

    Enum.find_value(@handlers, fn handler ->
      case handler.render(context) do
        {:emit, output} -> output
        :skip -> nil
      end
    end) || Renderer.interface(context.ts_name, context.fields)
  end

  def generate_all(category) do
    path = output_path(category)
    File.mkdir_p!(Path.dirname(path))
    File.write!(path, render_all(category))
  end

  def render_all(category) do
    category = category_name(category)

    header =
      "// AUTO-GENERATED by mix gen.contracts -- DO NOT EDIT\n// Source: #{category} contracts\n\n"

    body = Enum.map_join(list_contract_modules(category), "\n\n", &generate/1)

    header <> body <> "\n"
  end

  def derive_ts_name(mod) do
    mod
    |> Module.split()
    |> List.last()
  end

  defp contract?(module, category) do
    Code.ensure_loaded?(module) and function_exported?(module, :__contract__, 0) and
      module.__contract__() and contract_category?(module, category)
  end

  defp contract_category?(module, category) do
    function_exported?(module, :contract_category, 0) and
      case module.contract_category() do
        contract_category when is_atom(contract_category) ->
          category_name(contract_category) == category

        _other ->
          false
      end
  end

  def output_path(category) do
    category = category_name(category)
    Path.join(File.cwd!(), "assets/svelte/#{category}/contracts.generated.ts")
  end

  defp category_name(category) when is_atom(category),
    do: category |> Atom.to_string() |> category_name()

  defp category_name(category) when is_binary(category) do
    if Regex.match?(~r/^[a-z][a-z0-9_]*$/, category) do
      category
    else
      raise ArgumentError,
            "category must contain only lowercase letters, numbers, and underscores"
    end
  end

  defp category_name(_category), do: raise(ArgumentError, "category must be an atom or string")
end
